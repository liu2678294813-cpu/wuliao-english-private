import {execFileSync} from 'node:child_process';
import {readFileSync,writeFileSync} from 'node:fs';
import {resolve} from 'node:path';
import assert from 'node:assert/strict';
const adb=resolve('.android-sdk/platform-tools/adb.exe'),app='com.wuliao.english';
const out=resolve(process.argv[2] || 'output/recall-handwriting-20260920/upgrade-backup');
const run=(...args)=>execFileSync(adb,args,{encoding:'utf8',windowsHide:true,maxBuffer:64*1024*1024}).trim();
const manifest=()=>run('shell','run-as',app,'sh','-c',"'find app_webview app_hws_webview files shared_prefs no_backup -type f -exec sha256sum {} \\;' ").split('\n').map(s=>s.trim()).filter(Boolean).sort();
run('shell','am','force-stop',app);
const before=JSON.parse(readFileSync(resolve(out,'data-manifest.json'),'utf8'));
assert.deepEqual(manifest(),before,'User data changed since backup: take a fresh backup before installing');
assert.match(run('install','-r',resolve('output/android/wuliao-english-1.0.69.apk')),/Success/);
assert.deepEqual(manifest(),before,'Data files must be unchanged before the first upgraded launch');
const info=run('shell','dumpsys','package',app);
assert.match(info,/versionName=1\.0\.69/);assert.match(info,/versionCode=75/);
const result={installedAt:new Date().toISOString(),version:'1.0.69',versionCode:75,unchangedFiles:before.length,dataByteComparison:'identical'};
writeFileSync(resolve(out,'upgrade-result.json'),JSON.stringify(result,null,2));
run('shell','am','start','-n',`${app}/com.wuliao.english.MainActivity`);
console.log(JSON.stringify(result));
